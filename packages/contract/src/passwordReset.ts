/**
 * **비밀번호 재설정 메일이 있는가** — 화면과 서버가 함께 보는 **하나의 값** (O-010 · 2026-09-02).
 *
 * ══ 무엇이 문제였나 ══
 *
 * `POST /api/auth/password/forget` 이 `password_reset` 토큰을 DB 에 만들고
 * **60분 뒤 버린다.** 그런데 **저장소에 메일 발송 코드가 한 줄도 없다** —
 * nodemailer · resend · sendgrid · SMTP 전부 0건이다(2026-09-02 실측).
 * 관리자 화면에도 그 토큰을 꺼내 주는 곳이 없다.
 *
 * 즉 **토큰은 만들어지는데 사람에게 갈 길이 없다.** 비밀번호를 잊은 회원은
 * 영구히 못 들어온다. 그런데 응답은 `{"ok":true}` 였다.
 *
 * ══ 반쪽만 닫혀 있었다 (게시판과 같은 모양이다) ══
 *
 * ```
 * 화면   2026-09-02 에 닫혔다. 「아직 준비중입니다」 안내만 나온다        ← 고쳐져 있었다
 * API    ★그대로 200 {"ok":true} 를 돌려줬다★ (운영에서 직접 확인)      ← 안 고쳐져 있었다
 * ```
 * 화면 안의 상수 하나로 닫아서 **서버는 그 값을 몰랐다.** 게시판이 똑같았다(O-011).
 * 그래서 값을 계약으로 올린다 — 한 줄이 화면과 API 를 같이 움직인다.
 *
 * ══ 왜 메일을 붙이지 않았나 ══
 *
 * 메일 서비스를 붙이려면 계정·도메인 인증이 필요하고 그건 사장님 손이다.
 * **공개를 그것 때문에 늦출 이유가 없다.** 지금은 「없다」고 정직하게 말하고
 * 문의처로 안내한다. 라우트·토큰 발급·`/auth/password/reset`(토큰으로 실제 바꾸는 화면)은
 * **하나도 안 건드렸다** — 메일이 붙으면 이 한 줄로 그대로 돌아온다 (`CLAUDE.md` 1-4).
 *
 * ══ 켤 때 ══
 *
 * 메일 발송을 붙이고 이 값을 `true` 로 바꾼다. 그러면 옛 폼이 돌아오고 API 도 열린다.
 */
export const PASSWORD_RESET_MAIL_ENABLED: boolean = false

