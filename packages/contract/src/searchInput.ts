/**
 * 검색창에 **붙여 넣은 글자**를 조회 전에 다듬는다 (D-254).
 *
 * ── 왜 필요한가 (관측)
 *   `GET /api/players/name/{닉네임}` 은 앞뒤에 공백이 하나만 붙어도 404 다.
 *   운영 실측 (2026-09-01):
 *   ```
 *   /api/players/name/huwho    200   {"name":"huwho"}
 *   /api/players/name/%20huwho%20  404
 *   /api/players/name/huwho%20     404
 *   ```
 *   `findPlayerByName` 이 받은 글자를 그대로 `equals` 에 넣기 때문이다.
 *   **손으로 치면 안 붙는 공백이 붙여 넣으면 붙는다.** 그래서 붙여넣기에서만 터진다.
 *
 * ── 무엇을 지우는가 · 무엇을 안 지우는가
 *   ```
 *   지운다    앞뒤 공백(유니코드 공백 전부) · 폭 없는 문자(U+200B~200D · U+FEFF)
 *   안 지운다 가운데 공백 · 대소문자 · 전각/반각 · 특수문자
 *   ```
 *   **닉네임은 가운데 공백을 가질 수 있다.** 줄여 붙이면 없는 사람을 만들어 낸다.
 *   전각→반각 접기도 하지 않는다 — 전각으로 된 닉이 실제로 있는지 **[미확인]** 이고,
 *   접었다가 다른 사람이 걸리면 조용히 틀린 결과가 된다 (CLAUDE.md 3장 7번).
 *
 *   폭 없는 문자는 **화면에 보이지 않는다.** 그것이 섞이면 사용자는 왜 안 나오는지
 *   영영 알 수 없다. 그래서 이것만은 지운다 — 관측이 아니라 우리 결정이다.
 */

/** 폭 없는 문자 — 붙여넣기에 딸려 오고 화면에는 안 보인다 */
const ZERO_WIDTH = /[\u200B-\u200D\uFEFF]/g

/** 유니코드 공백 전부 (일반 공백 · NBSP · 전각 공백 등) */
const EDGE_SPACE = /^[\s\u00A0\u3000]+|[\s\u00A0\u3000]+$/g

/**
 * 붙여 넣은 검색어를 다듬는다. **비어 있으면 빈 문자열**이다.
 *
 * 다듬은 결과가 원본과 같을 수도 있다 — 그때는 아무 일도 일어나지 않는다.
 */
export function normalizePastedQuery(input: string): string {
  return input.replace(ZERO_WIDTH, '').replace(EDGE_SPACE, '')
}

/* ────────────────────────────────────────────────────────────────────────────
 * 못 찾았을 때 화면이 하는 말 (D-254)
 *
 * ── 왜 계약에 두나
 *   `CLAN_SEARCH_HINT` 와 같은 이유다 — 화면마다 문구를 새로 적으면 갈린다.
 *
 * ── 왜 두 갈래인가
 *   붙여넣기는 **두 가지 방식으로 실패한다.** 그걸 한 문장으로 뭉치면 사용자는
 *   자기가 무엇을 잘못했는지 알 수 없다.
 *   ```
 *   ① 주소는 알아봤다. 그런데 그 선수가 우리 기록에 없다   → 사용자 잘못이 아니다
 *   ② 주소로도 닉네임으로도 걸리는 게 없다                → 오타이거나 다른 사이트 주소다
 *   ```
 *   ①이 흔하다. 병영수첩 계정 번호로 우리 선수를 찾을 수 있는 비율이
 *   운영 실측 **2.1%(473/22,141)** 뿐이라서다. 그래서 ①은 "없다"가 아니라
 *   **"아직 없다"** 라고 말한다 — 사실이 그렇고, 나중에 생길 수 있다.
 * ──────────────────────────────────────────────────────────────────────────── */

/** 병영수첩 주소·계정 번호는 알아봤는데 그 선수가 아직 우리에게 없을 때 */
export const SEARCH_MISS_BARRACKS =
  '병영수첩 주소는 알아봤지만, 그 선수의 기록이 아직 없습니다.'

/** 붙여넣은 것을 아예 알아보지 못했을 때 (검색어를 그대로 되돌려 준다) */
export function searchMissMessage(query: string): string {
  return `‘${query}’ 로 찾은 결과가 없습니다.`
}

/** 조회 자체가 실패했을 때 — "없다" 와 구별한다. 없는 게 아니라 못 물어본 것이다 */
export const SEARCH_FAILED = '지금은 찾을 수 없습니다. 잠시 후 다시 시도해 주세요.'
