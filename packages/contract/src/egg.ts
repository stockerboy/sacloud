import { z } from 'zod'

/**
 * **깨진 알 목록** (`docs/EGG_SYSTEM_SPEC.md`).
 *
 * 화면은 「이 알이 깨졌나」를 알아야 마크를 빛나게 하고 가린 지표를 연다.
 * 그런데 깨짐의 **근거**(누가 · 언제 · 왜)는 공개할 것이 아니다 —
 * 관리자 강제인지 본인 인증인지는 관리자만 본다 (`GET /api/admin/eggs`).
 *
 * 그래서 공개 쪽은 **식별자만** 준다. 목록이 곧 상태다.
 *
 * ── 왜 통째로 주는가
 *   대상마다 물으면 갤러리 한 화면에 수십 번 왕복한다. 지금 깨진 알은 손에 꼽고,
 *   전부 깨져도 클랜 수백 · 선수 수천 줄의 **문자열 배열**이라 한 번에 받는 편이 싸다.
 *   그것이 부담이 될 만큼 깨지면 그때 리그별로 자르면 된다 (`league` 파라미터 자리를 비워 뒀다).
 */
export const EggBrokenList = z.object({
  /** 알이 깨진 선수 `Player.id` */
  players: z.array(z.string()),
  /** 알이 깨진 클랜 `Clan.slug` */
  clans: z.array(z.string()),
})
export type EggBrokenList = z.infer<typeof EggBrokenList>

/**
 * **알 시스템이 켜져 있는가** — 화면과 서버가 함께 보는 하나의 값 (O-026 · 2026-09-03).
 *
 * ══ 왜 계약으로 옮겼나 ══
 *
 * 이 값은 `packages/ui/src/egg/eggState.ts` 에 있었다. 그래서 **화면만 이 값을 보고
 * 서버는 몰랐다.** 알 시스템은 2026-09-01 에 껐는데(사용자 지시 — *"애초에 알시스템은
 * 걍 버려"*) `GET /api/eggs/broken` 은 **그대로 200 을 내고 있었다.**
 * 운영에서 확인했다 (2026-09-03) — 선수 4명 · 클랜 10곳의 식별자를 그대로 돌려줬다.
 *
 * 오늘 밤 같은 모양을 **세 번** 봤다.
 * ```
 * 게시판     화면만 닫힘 → 쓰기 API 8곳이 열려 있었다        (O-011)
 * 비번찾기   화면만 닫힘 → API 가 「보냈습니다」라고 답했다   (O-010)
 * 알         화면만 닫힘 → 목록 API 가 그대로 답했다          (여기)
 * ```
 * 서버가 `@sacloud/ui` 를 가져오면 React 가 딸려 오므로, **React 를 모르는 계약**으로
 * 값을 올리고 화면은 다시 내보내기만 한다. 한 줄이 화면과 API 를 같이 움직인다.
 *
 * ⚠ 지금 이 API 를 부르는 화면은 **없다** — `EggBoot` 이 이 값이 거짓이면 먼저 돌아간다.
 *   그래도 닫는 이유는, 열린 채로 두면 **아무도 안 쓰는 경로가 DB 를 때릴 수 있기**
 *   때문이다. 2026-09-01 에 이 경로가 실제로 500 을 냈다 (라우트 주석의 「⚠ 정정」).
 *
 * 되살릴 때는 이 한 줄을 `true` 로 바꾼다. 화면·API 가 같이 돌아온다.
 */
