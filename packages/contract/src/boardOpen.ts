/**
 * **게시판이 열려 있는가** — 화면과 서버가 함께 보는 **하나의 값** (O-011 · 2026-09-02).
 *
 * ══ 왜 여기(계약)에 있나 ══
 *
 * 이 값은 `packages/ui` 에 있었다(O-004). 그런데 화면만 보고 있어서
 * **문이 반쪽만 닫혀 있었다** — 아래 「무엇이 열려 있었나」 참조.
 * 서버 라우트가 `@sacloud/ui` 를 가져오면 React 가 딸려 온다. 그래서
 * **React 를 모르는 계약 쪽으로 값을 옮기고** 화면은 여기서 다시 내보낸다.
 * 이제 한 줄을 바꾸면 화면과 API 가 같이 움직인다.
 *
 * ══ ★무엇이 열려 있었나 (2026-09-02 실측)★ ══
 *
 * ```
 * 화면        홈에 게시판 링크가 없다. GNB 에서도 감췄다      ← 닫힌 것처럼 보였다
 * 주소        /board/free 는 200 이고 「글쓰기」 버튼도 있다   ← 실제로는 열려 있었다
 * 쓰기 API    개폐 검사가 **아예 없었다**                      ← 문이 활짝
 *             POST /api/boards · PUT/DELETE /api/boards/{id}
 *             POST /api/boards/{id}/votes
 *             POST /api/comments · PUT/DELETE /api/comments/{id}
 *             POST /api/comments/{id}/votes
 * 로그인      **비로그인이어도 비밀번호만 있으면 글이 써진다** (queries/boards.ts 633행)
 * 캡차        TODO. 실검증 없음 (queries/boards.ts 622행)
 * ```
 *
 * 즉 **주소를 아는 사람은 로그인 없이 계속 쓸 수 있었다.** 관리자는 자리에 없다.
 * 공개일에 천 명이 오고 그중 하나가 이걸 알면 도배가 시작된다.
 *
 * ══ ★읽기는 왜 안 막았나 — 내 판단이다 (박도현 · 2026-09-02)★ ══
 *
 * 지호가 「읽기까지 막을지는 네가 정하라」고 했다. **쓰기만 막았다.**
 *
 * ```
 * 1  막으려는 위험은 도배다. 그건 쓰기다. 읽기는 그 위험을 안 만든다
 * 2  읽기를 막으면 /board/** 화면이 통째로 깨진다. 손대는 면이 넓어지는데
 *    얻는 게 없다 — 어차피 홈에서 거기로 가는 길이 없다
 * 3  지금 들어 있는 글은 3건뿐이고 전부 우리가 8/23~8/28 에 남긴 시험 글이다.
 *    남이 쓴 것도, 해로운 것도 없다 (운영에서 직접 확인했다)
 * 4  홈이 이미 「게시판은 준비 중입니다」라고 말하고 있다 (O-006)
 * ```
 *
 * 나중에 읽기도 막아야 하면 같은 스위치로 한다. 지금 막을 이유가 없을 뿐이다.
 *
 * ⚠ 시험 글 3건 중 **둘의 제목이 `user001@naver.com`** 이다 — 시드 이메일 형식이
 *   제목에 들어가 있다. 가짜 주소지만 사람 눈에는 진짜로 보인다.
 *   **운영 글을 지우는 건 내 판단 밖이라** 지호에게 올렸다.
 *
 * ══ 열 때 하는 일 ══
 *
 * 이 값을 `true` 로 바꾸고 게시판으로 가는 길(GNB·푸터 링크)을 화면에 되살린다.
 * 그러면 홈 소개의 「게시판」 문단이 저절로 나오고(O-004) 「준비 중입니다」 줄이
 * 사라지며(O-006) 쓰기 API 가 열린다. **세 곳이 한 줄로 같이 움직인다.**
 *
 * ⚠ 열기 전에 확인할 것 — 사장님이 쓰신 게시판 정책은 「로그인해야 쓴다 + 제재」다.
 *   지금은 **비로그인도 써지고** 제재 도구가 있는지 확인 안 됐다.
 *   정책만 걸어 두고 못 지키면 없는 것보다 나쁘다.
 */
