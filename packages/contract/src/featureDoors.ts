/**
 * **화면 6개 밖으로 나가는 문** — 한 곳에서 여닫는다 (O-024 · 2026-09-03).
 *
 * ══ 왜 필요한가 ══
 *
 * `docs/STATE.md` 5장 규칙 5번은 「화면 6개 **밖의 기능을 새로 만들지 않는다**」다.
 * 그런데 **이미 있는 걸 감추는 판**이 없었다 — `O-011` 이 게시판만 닫았고 나머지는
 * 아무도 안 잡았다. 최윤서가 *「9 문 닫기가 반쪽이다」* 로 짚었다.
 *
 * **화면을 줄이는 것이 곧 공개일에 안 터지게 하는 일이다.**
 *
 * ══ 무엇을 끄고 무엇을 안 끄나 ══
 *
 * ```
 * 끈다   눈에 보이는 링크 하나
 * 안 끈다 라우트 · 파일 · DB · 주소로 직접 열기
 * ```
 * ⚠ **주소를 직접 치면 그대로 열려야 한다.** 404 를 내지 않는다 (`CLAUDE.md` 1-4).
 *   문을 잠그는 게 아니라 **안내판을 내리는 것**이다. 되살릴 때 한 줄만 바꾼다.
 *
 * ══ 왜 계약(`packages/contract`)에 있나 ══
 *
 * `packages/ui` 에 두면 **화면만 닫히고 서버는 열린 채로 남는다.** 이 저장소가
 * 그 사고를 세 번 냈다 (게시판 · 비밀번호 찾기 · 알 목록 — `boardOpen.ts` 참조).
 * 계약은 React 를 모르므로 서버 라우트도 같은 값을 볼 수 있다.
 * ★이 판에서는 **서버를 막지 않는다** — 위 「안 끈다」 그대로다. 그래도 값은 여기 둔다.
 *   나중에 서버까지 닫아야 할 때 **옮길 필요가 없어야** 한다.★
 */

