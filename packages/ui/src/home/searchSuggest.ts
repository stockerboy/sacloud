/**
 * 홈 검색 자동완성 — **스위치와 부하 규칙 한 곳** (O-002 · 2026-09-02).
 *
 * ══ 왜 이 파일이 따로 있나 ══
 *
 * 홈은 지금 엣지 캐시라 사람이 아무리 몰려도 서버에 안 닿는다. 그런데 자동완성은
 * **글자를 칠 때마다 DB 로 간다.** 새는 곳이 여기 하나뿐이므로 규칙도 여기 하나에 둔다.
 * 부하가 감당이 안 되면 아래 `SEARCH_SUGGEST_ENABLED` **한 줄만 false 로** 바꾸면
 * 자동완성이 통째로 사라지고 지금까지의 검색 그대로 돌아온다 (`CLAUDE.md` 1-4).
 *
 * ══ 왜 자동완성이 필요한가 (B 가 운영에서 직접 재서 얻은 숫자) ══
 *
 * ```
 * 선수는 이름을 한 글자도 안 틀리고 다 쳐야 찾아진다
 *   Jaehyunpark  200      Jaehyun  404      tsArbban  404      xe  404
 * 클랜은 부분으로도 찾아진다 — 같은 「이름으로 찾기」인데 둘이 다르다
 *   Mira  200 (MiraGe.)   tsAr  200 (-tsAr.nTc)
 * 그런데 표본 110명 중 44명(40%)이 이름에 ☆ ♡ ♥ : ` . - 를 갖고 있다
 *   Shark☆  soultree♥  o(≥∇≤o)`pL  SC4..김지훈
 * ```
 * 폰에서 저걸 정확히 치는 것은 사실상 불가능하다. **기록은 DB 에 멀쩡히 있는데도**
 * 「‘…’ 로 찾은 결과가 없습니다」를 보고 나간다.
 *
 * ⚠ 표본 주의 — 40% 는 자동완성으로 모은 110명 안의 비율이지 전체 22,141명의 비율이 아니다.
 *
 * ══ 새로 만든 것이 없다 ══
 *
 * 부르는 API 셋은 **이미 있었고 운영에서 잘 돌고 있었다** (`endpoints.ts` 243·257·271행).
 * 화면에서 쓰는 곳이 리그 설정 한 군데뿐이라 아무도 몰랐을 뿐이다.
 */

/**
 * 자동완성을 켤 것인가. **끄려면 이 줄만 `false` 로.**
 *
 * 끄면 후보 목록이 아예 안 그려지고 요청도 안 나간다. 검색창·엔터·못 찾음 문구는
 * 하나도 안 바뀐다 — 자동완성은 그 위에 **얹은** 것이지 대체가 아니다.
 */
export const SEARCH_SUGGEST_ENABLED: boolean = true

/**
 * 몇 글자부터 부를 것인가.
 *
 * 한 글자에 부르면 `a` 하나에 수천 건이 걸리고, 사람들이 검색창을 누를 때마다
 * 요청이 나간다. 두 글자부터가 「찾을 마음이 생긴」 지점이다.
 */
export const SUGGEST_MIN_CHARS = 2

/**
 * 마지막 타이핑 뒤 이만큼 기다렸다가 부른다 (밀리초).
 *
 * 사람이 이름 하나를 치는 동안 글자 수만큼 요청이 나가면 안 된다.
 * `Jaehyunpark` 11글자를 쳐도 요청은 몇 건에 그쳐야 한다.
 */
export const SUGGEST_DEBOUNCE_MS = 300

/** 몇 개까지 그릴 것인가. 서버가 더 줘도 여기서 자른다 */
export const SUGGEST_MAX_ITEMS = 8

/**
 * 받아 둔 결과를 몇 개까지 기억할 것인가.
 *
 * 한 글자 지웠다가 다시 치는 일이 잦다 (`Jaehyu` → `Jaehy` → `Jaehyu`).
 * 그때 이미 받아 둔 것을 다시 쓰면 요청이 아예 안 나간다.
 * 홈을 떠나면 사라지는 기억이라 크게 잡을 이유가 없다.
 */
export const SUGGEST_CACHE_MAX = 30

/**
 * 후보 한 줄.
 *
 * **`packages/ui` 는 API 를 모른다.** 부르고 고르는 것은 화면 쪽(`app/_home/HomeSearch.tsx`)이
 * 하고, 여기는 그려 줄 모양만 받는다 — `onSubmit` 을 그렇게 나눠 둔 것과 같은 규칙이다.
 */
export interface SearchSuggestion {
  /** 누르면 갈 곳을 정하는 값. 선수는 `id`, 클랜·리그는 `slug` */
  key: string
  /** 크게 보일 이름 */
  name: string
  /** 이름 아래 흐리게 붙일 한 줄. 선수면 소속 클랜명. 없으면 생략 */
  sub?: string | null
}
