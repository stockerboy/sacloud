/**
 * 공식 라벨 · 래더 반영 문구 (D-145 에서 의미가 바뀌었다).
 *
 * ── 무엇이 바뀌었나
 *   예전에는 `공식 경기`(양 팀 중 한쪽이라도 본클랜원 3명 이상)만 래더에 반영됐다.
 *   **D-145 에서 그 게이트를 폐기했다.** 정상 5v5 + 참가자 10명이면 전부 반영된다 —
 *   클1용4 vs 클1용4 도 점수를 받는다.
 *
 *   그래서 `공식/비공식`은 이제 **역사적 라벨**일 뿐 래더와 무관하다.
 *   래더 반영 여부를 정하는 것은 **참가자 구성이 5v5 인가** 하나다.
 *
 * ── 왜 이 파일이 따로 있는가
 *   반영되지 않은 경기에 "반영" 문구가 뜨거나 그 반대가 되면 사용자가 바로 오해한다.
 *   실제로 그렇게 나갔던 적이 있어 분기를 순수 함수로 떼어 두고 테스트로 고정한다.
 */

/** 정상 경기 한 팀 인원 */
const SQUAD_SIZE = 5

/*
 * `비공식 경기` 배지는 **없앴다** (D-149).
 *
 * D-145 에서 `official` 은 래더 자격도 가중치도 아니게 됐다. 그런데 배지로 남겨 두면
 * 화면이 "비공식이라 점수를 덜 준다"는 폐기된 규칙을 계속 말하게 된다.
 * 사용자에게 필요한 상태는 **래더에 반영됐는가** 하나뿐이다.
 *
 * `Match.official` 값 자체는 지우지 않았다 — 출처(provenance)·관리자 화면에서 쓴다.
 * 다만 **일반 사용자 화면에 배지로 노출하지 않는다.**
 */

/** 래더에 반영되지 않은 경기 배지 */
export const NOT_RATED_BADGE = '래더 미반영'

export const NOT_RATED_BADGE_TITLE =
  '참가자 10명(5대5)이 확인되지 않아 래더에 반영되지 않습니다. 기록은 그대로 남습니다'

/**
 * 이 경기가 래더에 반영되는가.
 *
 * **`official` 을 보지 않는다** (D-145). 정상 5v5 인지만 본다.
 *
 * @param completeness `5v5` 처럼 확인된 출전 인원 표기. 모르면 null
 */
export function isRated(completeness: string | null): boolean {
  return completeness === `${SQUAD_SIZE}v${SQUAD_SIZE}`
}

/** 경기 상세에 붙는 래더 반영 안내 */
export function ladderNotice(completeness: string | null): string {
  return isRated(completeness)
    ? '정상 5대5 경기 — 용병 포함 출전 전원이 개인 래더 100% 반영, 두 클랜 모두 클랜 래더 반영'
    : '참가자 10명이 확인되지 않아 래더에 반영되지 않습니다 (기록은 남습니다)'
}

/**
 * 클랜 구성 안내.
 *
 * 예전의 **반영률(100/70/40/0%)은 폐기됐다** — 클랜원 수가 증감을 깎지 않는다.
 * 대신 최근 20경기 평균 본클랜원 수가 **상한 +50 의 구성 보정**으로만 반영된다.
 * 그래서 경기 한 건에 붙는 "이 경기의 반영률" 이라는 개념 자체가 없어졌다.
 */
export const COMPOSITION_NOTICE =
  '클랜원 수는 이 경기의 증감을 깎지 않습니다. 최근 20경기 평균 클랜원 수가 클랜 점수에 최대 +50까지 반영됩니다'

/**
 * 래더 증감 자리에 쓰는 짧은 표기 (D-149).
 *
 * 예전에는 `알수없음` 이었다. 그건 **틀린 말**이다 — 우리는 그 경기가 래더에 반영되지
 * 않았다는 것을 정확히 안다. 모르는 게 아니라 **없는** 것이다.
 * `알수없음` 은 값을 정말 모를 때만 쓴다 (딜량·헤드샷 결측 등 · `CLAUDE.md` 6장).
 */
export const NOT_RATED_INLINE = '미반영'

