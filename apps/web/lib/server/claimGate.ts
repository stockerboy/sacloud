import { CLAIM_DOORS_OPEN } from '@sacloud/contract'
import { forbidden } from './respond'

/**
 * **승인자가 없는 신청 문** — 닫혀 있으면 여기서 막는다 (O-008 ⑥ · 2026-09-03).
 *
 * ══ 왜 필요했나 — 네 번째다 ══
 *
 * `O-024` 로 화면 링크를 껐다. 그런데 **`CLAIM_DOORS_OPEN` 을 읽는 곳이 화면뿐이었다.**
 * ```
 * 그 상수를 읽는 라우트   app/api/** 에 ★0개★
 * 그래서 지금도 받는다     PUT /api/me/link
 *                        POST /api/clans/{slug}/master-claim
 * ```
 * **주소를 아는 사람은 계속 신청할 수 있었고, 받아 줄 사람은 자리에 없다.**
 * 최윤서가 잡았다.
 *
 * ⚠ `O-024` 가 거짓말을 한 건 아니다 — 그 판은 확인 칸에
 *   *「문을 잠근 게 아니라 안내판을 내렸다」* 고 정직하게 적었다.
 *   **문제는 그걸 「닫혔다」로 세면 안 된다는 것이다.**
 *
 * ══ 이 병을 이 저장소가 몇 번 앓았나 ══
 *
 * ```
 * O-010  비밀번호 찾기   화면만 닫힘, 서버는 토큰을 계속 만들고 있었다
 * O-011  게시판         화면만 닫힘, 쓰기 API 에 개폐 검사가 아예 없었다
 * O-026  알 목록        화면만 닫힘, 서버는 식별자를 계속 내주고 있었다
 * O-008⑥ 신청 둘        ★이번★
 * ```
 * 그래서 `featureDoors.ts` 를 **계약**에 두었다 — 서버가 같은 값을 볼 수 있게.
 * **이제 그 값을 실제로 읽는다.**
 *
 * ══ 왜 403 인가 ══
 *
 * `404` 는 「그런 것이 없다」는 뜻이고, 이 신청 창구는 **있다. 지금 안 받을 뿐이다.**
 * 나중에 열 때 같은 주소가 그대로 산다. 없다고 말하면 그건 거짓말이다.
 */
export const CLAIM_CLOSED_MESSAGE =
  '지금은 신청을 받지 않습니다. 승인해 드릴 준비가 되면 다시 열겠습니다.'

/** 닫혀 있으면 403, 열려 있으면 `null` — 부르는 쪽은 `null` 일 때만 계속한다 */
export function claimClosed(): Response | null {
  return CLAIM_DOORS_OPEN ? null : forbidden(CLAIM_CLOSED_MESSAGE)
}
