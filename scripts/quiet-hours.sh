#!/bin/sh
# ★★무거운 일은 「사람 없는 시간」 에만 한다★★ (2026-09-20 · 사장님)
#
# ⚠ ★★오전 7시 ~ 오후 1시★★ 다. 새벽이 아니다.
#
#   > 「무거운 일은 오전 7시부터 오후1시까지 끝내 그때가 사람 젤없어
#   >  이게임은 밤에 많이해」 — 사장님, 2026-09-20
#
#   처음에는 ★밤 11시~아침 7시★ 로 잡았는데 ★정반대★ 였다.
#   서든어택은 ★밤에 사람이 몰린다.★ 경기도 밤에 쏟아지고, 사이트도 밤에 붐빈다.
#   그 시간에 무거운 일을 돌리면 ★제일 많은 사람이 제일 느린 사이트를 본다.★
#   ⚠ 옛 이름은 `night-heavy.sh` 였다 — `git mv` 로 옮겼으니 이력에 남아 있다.
#
# > 「사이트 중간중간 버벅대고 느린거 진짜 왜이러는거야」
# > 「아직도 느린데… 왜이래 진짜 사람들 많이 들어오면 어쩌려고 이러는거야」
#
# ── 왜 만들었나 (실측으로 잡았다)
#
#   기록을 채우는 배치가 낮에 돌면 ★사이트가 10~25배 느려진다.★
#   ```
#     배치 4개가 돌 때   검색 13~25초 · 경기상세 25초 (500 나기도)
#     배치를 멈춘 뒤     검색 0.4초   · 경기상세 0.4초
#   ```
#   ★사람이 쓰는 시간이 기록을 채우는 것보다 먼저다.★ 기록은 낮에 채우면 된다.
#
# ── 여기서 하는 일 (순서대로 · ★한 번에 하나씩★)
#   ```
#   ① 클랜 이름표 채우기      71만 줄 남음 — 제일 무겁다
#   ② MVP 설명 다시 만들기    「한 라운드 3킬」 을 과거 경기에도 붙인다
#   ```
#
# ⚠ ★동시에 돌리지 않는다.★ 둘이 겹치면 조용한 시간에도 사이트가 느려진다.
# ⚠ ★끝나는 시각을 지킨다★ — 아침 7시가 되면 하던 일을 접는다.
#   사람이 들어오기 시작하는 시각이다. 내일 같은 시간에 이어서 하면 된다.
set -u
cd "$(dirname "$0")/.." || exit 1
. /root/sacloud.env 2>/dev/null || true

LOG="${QUIET_LOG:-/root/log/quiet.log}"
# ★일을 시작하는 시각★ · ★접는 시각★ — 사장님이 정하신 7시~13시
START_HOUR="${QUIET_START_HOUR:-7}"
STOP_HOUR="${QUIET_STOP_HOUR:-13}"

say() { printf '%s | %s\n' "$(date '+%m-%d %H:%M')" "$1" | tee -a "$LOG"; }

# ★조용한 시간이 지났나★ — 지났으면 아무것도 시작하지 않는다
#   ⚠ 7시 ★이전★ 도 일하지 않는다 — 그때는 아직 새벽이라 ★사람이 남아 있다.★
past_quiet() {
  h=$(date +%-H)
  [ "$h" -ge "$STOP_HOUR" ] || [ "$h" -lt "$START_HOUR" ]
}

if past_quiet; then
  say "지금은 사람이 있는 시간이다 — 무거운 일은 하지 않는다 (${START_HOUR}시~${STOP_HOUR}시에만 한다)"
  exit 0
fi

say "★조용한 시간 작업 시작★ (${STOP_HOUR}시에 접는다)"

# ── ① 클랜 이름표 채우기 ──────────────────────────────────────────
#   한 판 1,000줄 · 약 1분. 아침이 되면 그 자리에서 멈춘다.
for i in $(seq 1 400); do
  past_quiet && { say "사람이 오는 시간이다 — ① 을 여기서 접는다"; break; }
  out=$(pnpm --filter @sacloud/worker nexon clan-name-backfill --confirm --limit 1000 2>&1 | grep "읽음=" || true)
  say "  ① $out"
  case "$out" in
    *"읽음=0"*) say "  ① ★다 채웠다★"; break ;;
    '')         say "  ① 출력을 못 읽었다 — 30초 쉬고 다시"; sleep 30; continue ;;
  esac
  sleep 5
done

# ── ①-2 클랜 이름표 다시 만들기 (2026-09-23 밤 · 자이언트 누락 원인) ──────
#   옛 이름표는 상대 이름까지 「내 옛 이름」 으로 담아 투영이 310개 이름을 버렸다.
#   덮기(set cover)로 다시 쓴다. 원문 76만 줄을 한 번 훑으니 밤에만.
if past_quiet; then
  say "사람이 오는 시간이다 — ①-2 는 내일 같은 시간에 한다"
else
  out=$(pnpm --filter @sacloud/worker nexon clan-alias-rebuild --confirm 2>&1 | grep "이름표" | tail -1 || true)
  say "  ①-2 이름표 다시 만듦 — ${out:-(출력을 못 읽었다)}"
fi

# ── ①-3 정규화 깊은 되감기 (2026-09-23 밤) ─────────────────────────
#   2분 예약은 「이미 만든 곳 − 2시간」 부터만 본다. 그보다 늦게 도착한 원문(상대가 며칠 뒤에
#   긁힌 경기)은 영영 안 만들어진다 — deluxe 5,944건이 그렇게 빠졌다. 하루 한 번 30시간을 되감는다.
if past_quiet; then
  say "사람이 오는 시간이다 — ①-3 은 내일 같은 시간에 한다"
else
  say "  ①-3 정규화 30시간 되감기 시작"
  PROJECT_REWIND_HOURS=30 flock -w 600 /var/lock/sac-project.lock sh scripts/project.sh >> "$LOG" 2>&1
  say "  ①-3 끝 (코드 $?)"
fi

# ── ② MVP 설명 다시 만들기 ────────────────────────────────────────
#   ⚠ ★①이 끝난 뒤에만★ 한다. 둘이 겹치면 밤에도 사이트가 느려진다.
if past_quiet; then
  say "사람이 오는 시간이다 — ② 는 내일 같은 시간에 한다"
else
  say "  ② MVP 설명 다시 만들기 시작"
  pnpm --filter @sacloud/worker nexon player-hex-build --confirm --rebuild >> "$LOG" 2>&1
  say "  ② 끝 (코드 $?)"
fi

say "★조용한 시간 작업 끝★"
